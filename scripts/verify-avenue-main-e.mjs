import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import * as THREE from 'three';
import {createMainTowerFacade} from '../src/main-tower-facade.js';
import {avenuePavingGeometry} from '../src/avenue-paving.js';
import {bounds} from '../src/geo.js';
const d=JSON.parse(readFileSync(new URL('../public/data/campus.json',import.meta.url),'utf8'));
const e=d.buildings.find(b=>b.osmId===263624057);
assert(e,'Main E OSM footprint missing');
const group=createMainTowerFacade({footprint:bounds(e.points),height:e.height,baseY:1.1});
assert(group.children.filter(m=>m.isMesh).length===4,'Main E material group mismatch');
assert(group.children.every(m=>m.geometry.attributes.position.count>0),'Empty facade mesh');
const b=new THREE.Box3().setFromObject(group),[x0,z0,x1,z1]=bounds(e.points);
assert(b.min.x>=x0-.55&&b.max.x<=x1+.55,'Main E facade spills outside east-west footprint');
assert(b.min.z>=z0-1.6&&b.max.z<=z1+1.6,'Main E facade spills outside north-south footprint');
assert(b.max.y<=1.1+e.height+.01,'Facade height over source-based estimated height');
const road=avenuePavingGeometry(d.roads);
assert.equal(road.roadName,'梧桐东道');
assert(road.length>200&&road.sidewalks.length>=2&&road.edges.length>=2);
for(const geo of [...road.sidewalks,...road.edges])assert([...geo.attributes.position.array].every(Number.isFinite));
console.log(JSON.stringify({passed:true,mainETowerBounds:{min:b.min.toArray(),max:b.max.toArray()},mainEMaterials:group.children.length,roadName:road.roadName,roadLength:road.length}));
