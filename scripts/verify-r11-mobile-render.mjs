import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {renderPixelRatio,keepOrbitAboveGround,framePercentiles,enableFarFoliageCoverage} from '../src/mobile-render-stability.js';
const low=renderPixelRatio({width:390,height:844,deviceRatio:2,quality:'low'});
const high=renderPixelRatio({width:390,height:844,deviceRatio:2,quality:'high'});
const native=renderPixelRatio({width:390,height:844,deviceRatio:1,quality:'high'});
assert.equal(low,1.5);
assert.equal(high,1.8);
assert.equal(native,1);
assert.ok(768*1024*renderPixelRatio({width:768,height:1024,deviceRatio:3,quality:'high'})**2<=2350001);
assert.equal(renderPixelRatio({width:1440,height:900,deviceRatio:2,quality:'low'}),1.8);
const camera={position:{y:-5}};
assert.equal(keepOrbitAboveGround(camera,1.1),true);
assert.ok(camera.position.y>=4.3);
assert.equal(keepOrbitAboveGround(camera,1.1),false);
assert.deepEqual(framePercentiles([.010,.020,.030,.040]),{p50Ms:20,p95Ms:40});
const material={alphaTest:.26,alphaToCoverage:false,map:{}};
const mock={group:{traverse(fn){fn({isInstancedMesh:true,material});}}};
assert.equal(enableFarFoliageCoverage(mock,{SAMPLES:1,getParameter(){return 4}}),1);
assert.equal(material.alphaToCoverage,true);
assert.equal(material.needsUpdate,true);
assert.equal(enableFarFoliageCoverage(mock,{SAMPLES:1,getParameter(){return 0}}),0);
const world=readFileSync(new URL('../src/world.js',import.meta.url),'utf8');
assert.ok(world.includes("cv.addEventListener('webglcontextrestored'"));
assert.ok(world.includes('keepOrbitAboveGround(this.camera,BASE)'));
assert.ok(world.includes('devicePixelRatio!==this.lastDeviceRatio'));
assert.ok(world.includes('renderPixelRatio({width:w,height:h'));
console.log(JSON.stringify({passed:true,low,high,native,foliageCoverage:true,contextRestorationHook:true,orbitSafe:true,deviceRatioChange:true}));
